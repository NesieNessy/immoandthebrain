#!/usr/bin/env node
/**
 * Generates supabase/migrations/20260926000001_postal_code_state.sql — the
 * PLZ → Bundesland table behind the Grunderwerbsteuer rate of the
 * Detailbewertung's Kaufkosten step.
 *
 * Source: OpenPLZ API (https://openplzapi.org, data from the official
 * municipality and postal-code directories), which the app already uses for
 * the postal-code → city lookup. Every locality of every federal state is
 * fetched; a postal code shared by localities in two states (a handful sit on
 * state borders) is assigned to the state holding most of its localities, and
 * listed in the migration header.
 *
 * Re-run to refresh the data:  node scripts/generate-postal-code-states.cjs
 */
const fs = require('node:fs');
const path = require('node:path');

const API = 'https://openplzapi.org/de';
const PAGE_SIZE = 50;
const OUTPUT = path.join(__dirname, '..', 'supabase', 'migrations', '20260926000001_postal_code_state.sql');

// Official state keys (AGS) → the two-letter codes used by state_acquisition_costs.
const STATE_BY_KEY = {
  '01': 'SH', '02': 'HH', '03': 'NI', '04': 'HB', '05': 'NW', '06': 'HE', '07': 'RP', '08': 'BW',
  '09': 'BY', '10': 'SL', '11': 'BE', '12': 'BB', '13': 'MV', '14': 'SN', '15': 'ST', '16': 'TH',
};

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

async function getJson(url) {
  for (let attempt = 1; ; attempt++) {
    const response = await fetch(url, { headers: { Accept: 'application/json' } });
    if (response.ok) return { body: await response.json(), headers: response.headers };
    if (attempt >= 4) throw new Error(`${url} → HTTP ${response.status}`);
    await sleep(1000 * attempt);
  }
}

async function main() {
  /** postal code → { state → number of localities } */
  const counts = new Map();

  for (const [key, state] of Object.entries(STATE_BY_KEY)) {
    let totalPages = 1;
    for (let page = 1; page <= totalPages; page++) {
      const { body, headers } = await getJson(`${API}/FederalStates/${key}/Localities?page=${page}&pageSize=${PAGE_SIZE}`);
      totalPages = Number(headers.get('x-total-pages') ?? 1);
      for (const locality of body) {
        if (!/^\d{5}$/.test(locality.postalCode ?? '')) continue;
        const perState = counts.get(locality.postalCode) ?? {};
        perState[state] = (perState[state] ?? 0) + 1;
        counts.set(locality.postalCode, perState);
      }
      await sleep(100); // be polite to the public API
    }
    process.stdout.write(`${state} `);
  }

  const rows = [];
  const shared = [];
  for (const postalCode of [...counts.keys()].sort()) {
    const perState = Object.entries(counts.get(postalCode)).sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));
    rows.push([postalCode, perState[0][0]]);
    if (perState.length > 1) shared.push(`${postalCode}: ${perState.map(([state, n]) => `${state} (${n})`).join(', ')}`);
  }

  const header = [
    '-- PLZ → Bundesland, for the Grunderwerbsteuer rate of the Detailbewertung',
    '-- (Kaufkosten). Replaces the two-digit-prefix approximation, which put',
    '-- postal codes that straddle a state border (e.g. Potsdam 144xx, Harburg',
    '-- 210xx) into the wrong state. The code keeps that approximation only as a',
    '-- fallback for postal codes missing here (e.g. Großkunden-PLZ).',
    '--',
    '-- GENERATED by scripts/generate-postal-code-states.cjs from the OpenPLZ API',
    `-- (${rows.length} postal codes). Re-run the script to refresh; do not edit by hand.`,
    '--',
    `-- Postal codes with localities in more than one state (${shared.length}) —`,
    '-- assigned to the state with most of them:',
    ...shared.map((line) => `--   ${line}`),
    '',
    'CREATE TABLE IF NOT EXISTS postal_code_state (',
    '    postal_code  CHAR(5)  PRIMARY KEY CHECK (postal_code ~ \'^[0-9]{5}$\'),',
    '    state        CHAR(2)  NOT NULL REFERENCES state_acquisition_costs(state)',
    ');',
    '',
    "COMMENT ON TABLE postal_code_state IS 'Bundesland je Postleitzahl (Quelle: OpenPLZ). Grundlage der Grunderwerbsteuer in der Detailbewertung.';",
    '',
  ];

  const values = rows.map(([postalCode, state]) => `    ('${postalCode}', '${state}')`).join(',\n');
  const body = [
    'INSERT INTO postal_code_state (postal_code, state) VALUES',
    values,
    'ON CONFLICT (postal_code) DO UPDATE SET state = EXCLUDED.state;',
    '',
    '-- Shared reference data: readable by any authenticated user, never writable',
    '-- from the client (same pattern as state_acquisition_costs).',
    'ALTER TABLE postal_code_state ENABLE ROW LEVEL SECURITY;',
    'DROP POLICY IF EXISTS "Authenticated users can view postal code states" ON postal_code_state;',
    'CREATE POLICY "Authenticated users can view postal code states"',
    '    ON postal_code_state FOR SELECT',
    "    USING (auth.role() = 'authenticated');",
    '',
  ];

  fs.writeFileSync(OUTPUT, [...header, ...body].join('\n'));
  console.log(`\nWrote ${rows.length} postal codes (${shared.length} shared) to ${path.relative(process.cwd(), OUTPUT)}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
